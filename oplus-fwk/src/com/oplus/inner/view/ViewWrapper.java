package com.oplus.inner.view;

public class ViewWrapper {
    public static void setScrollXForColor(android.view.View view, int scrollX) {
        if (view != null) view.setScrollX(scrollX);
    }
    public static void setScrollYForColor(android.view.View view, int scrollY) {
        if (view != null) view.setScrollY(scrollY);
    }
}
